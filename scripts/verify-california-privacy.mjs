import { createRequire } from "node:module";
import { createServer } from "node:http";
import { readFile } from "node:fs/promises";
import { extname, join, normalize, resolve } from "node:path";
const require = createRequire(import.meta.url);
const { chromium } = require("playwright");
const root = resolve(import.meta.dirname, "..");
const types = { ".html":"text/html", ".js":"text/javascript", ".css":"text/css", ".webp":"image/webp", ".png":"image/png", ".jpg":"image/jpeg", ".xml":"application/xml" };
const server = createServer(async (req,res) => { try { const pathname = decodeURIComponent(new URL(req.url,"http://localhost").pathname); const rel = pathname === "/" ? "index.html" : pathname.replace(/^\//,""); const file = normalize(join(root, rel)); if (!file.startsWith(root)) throw new Error("bad path"); const data = await readFile(file); res.writeHead(200,{"Content-Type":types[extname(file)]||"application/octet-stream"}); res.end(data); } catch { res.writeHead(404); res.end("Not found"); } });
await new Promise((ok)=>server.listen(4194,"127.0.0.1",ok));
const base = "http://127.0.0.1:4194";
const failures=[]; const check=(value,message)=>{if(!value)failures.push(message)};
const browser = await chromium.launch({ headless:true, executablePath:process.env.CHROME_PATH||"C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe" });
const context = await browser.newContext();
let page = await context.newPage();
await page.goto(`${base}/index.html`,{waitUntil:"networkidle"});
check((await context.cookies()).length===0,"Cookie exists before visitor choice");
check(await page.locator("[data-privacy-banner]").isVisible(),"First-visit privacy banner is not visible");
await page.locator("[data-continue-without-saving]").click();
check((await context.cookies()).length===0,"Continue without saving created a cookie");
check(!(await page.locator("[data-privacy-banner]").isVisible()),"Continue without saving did not dismiss banner");
await page.reload({waitUntil:"networkidle"});
check(await page.locator("[data-privacy-banner]").isVisible(),"Unsaved choice incorrectly persisted");
await page.locator("[data-privacy-banner] [data-reject-optional]").click();
const cookies = await context.cookies(); const choice = cookies.find((cookie)=>cookie.name==="4oh_privacy_choice");
check(cookies.length===1,"Opt-out created more than one cookie");
check(choice?.value==="optional_off","Opt-out cookie value is wrong");
check(choice?.secure===true,"Opt-out cookie is not Secure");
check(choice?.sameSite==="Lax","Opt-out cookie is not SameSite=Lax");
check(choice?.expires>Date.now()/1000+150*86400,"Opt-out cookie retention is shorter than disclosed");
await page.reload({waitUntil:"networkidle"});
check(!(await page.locator("[data-privacy-banner]").isVisible()),"Saved opt-out was not remembered");
await page.locator("footer [data-open-privacy]").click();
check(await page.locator("[data-privacy-dialog]").isVisible(),"Footer privacy control did not open dialog");
check((await page.locator("[data-privacy-dialog] input:not(:checked)").count())===3,"Optional categories are not visibly off");
await page.keyboard.press("Escape");
await page.goto(`${base}/privacy.html`,{waitUntil:"networkidle"});
await page.locator("[data-forget-privacy]").click();
check((await context.cookies()).length===0,"Clear choice did not remove cookie");
check(await page.locator("[data-privacy-banner]").isVisible(),"Banner did not return after clearing choice");
await context.close();
const gpcContext = await browser.newContext();
await gpcContext.addInitScript(()=>Object.defineProperty(Navigator.prototype,"globalPrivacyControl",{configurable:true,get:()=>true}));
page = await gpcContext.newPage(); await page.goto(`${base}/privacy.html`,{waitUntil:"networkidle"});
check(!(await page.locator("[data-privacy-banner]").isVisible()),"Banner asks again despite GPC opt-out");
check((await page.locator("[data-gpc-status]").first().innerText()).includes("honored"),"GPC status is not acknowledged");
check((await gpcContext.cookies()).length===0,"GPC handling created a cookie");
await gpcContext.close();
for (const width of [320,375,430]) { const p=await browser.newPage({viewport:{width,height:812},hasTouch:true}); const errors=[]; p.on("pageerror",e=>errors.push(e.message)); await p.goto(`${base}/privacy.html`,{waitUntil:"networkidle"}); check((await p.evaluate(()=>document.documentElement.scrollWidth-innerWidth))<=1,`Privacy page overflows at ${width}px`); check(await p.locator("[data-privacy-banner]").isVisible(),`Banner not visible at ${width}px`); check(errors.length===0,`Runtime error at ${width}px: ${errors.join(", ")}`); await p.close(); }
await browser.close(); await new Promise((ok)=>server.close(ok));
if(failures.length){console.error(failures.map(x=>`- ${x}`).join("\n"));process.exit(1)}
console.log("California privacy verification passed: default-off banner, no pre-choice storage, remembered rejection, clearing, GPC, dialog, cookie attributes, and 320/375/430px layouts.");